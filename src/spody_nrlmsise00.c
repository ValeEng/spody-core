/* ZETA statement function: geopotential altitude difference. */
static double zeta(double re, double zz, double zl)
{
    return (zz - zl) * (re + zl) / (re + zz);
}

/* GLATF: latitude-dependent gravity (cm/s^2) and effective radius (km). */
static void glatf(double lat, double *gv, double *reff)
{
    double c2 = cos(2.0 * DGTR * lat);
    *gv = 980.616 * (1.0 - 0.0026373 * c2);
    *reff = 2.0 * (*gv) / (3.085462E-6 + 2.27E-9 * c2) * 1.0E-5;
}

/* CCOR: chemistry/dissociation correction. */
static double ccor(double alt, double r, double h1, double zh)
{
    double e = (alt - zh) / h1;
    double c;
    if (e > 70.0)
        c = 0.0;
    else if (e < -70.0)
        c = r;
    else
        c = r / (1.0 + exp(e));
    return exp(c);
}

/* CCOR2: O & O2 chemistry/dissociation correction. */
static double ccor2(double alt, double r, double h1, double zh, double h2)
{
    double e1 = (alt - zh) / h1;
    double e2 = (alt - zh) / h2;
    double c;
    if (e1 > 70.0 || e2 > 70.0)
        c = 0.0;
    else if (e1 < -70.0 && e2 < -70.0)
        c = r;
    else
        c = r / (1.0 + 0.5 * (exp(e1) + exp(e2)));
    return exp(c);
}

/* SCALH: scale height (km). */
static double scalh(const Msis *m, double alt, double xm, double temp)
{
    double g = m->gsurf / ((1.0 + alt / m->re) * (1.0 + alt / m->re));
    return RGAS * temp / (g * xm);
}

/* DNET: turbopause correction (root-mean density of the diffusive and
 * fully-mixed profiles). The Fortran prints 'DNET LOG ERROR' on the
 * degenerate branches; they are unreachable for valid inputs and fail
 * quiet here. */
static double dnet(double dd, double dm, double zhm, double xmm, double xm)
{
    double a = zhm / (xmm - xm);
    double ylog;
    if (!(dm > 0.0 && dd > 0.0)) {
        if (dd == 0.0 && dm == 0.0)
            dd = 1.0;
        if (dm == 0.0)
            return dd;
        if (dd == 0.0)
            return dm;
    }
    ylog = a * log(dm / dd);
    if (ylog < -10.0)
        return dd;
    if (ylog > 10.0)
        return dm;
    return dd * pow(1.0 + exp(ylog), 1.0 / a);
}

/* SPLINE: second derivatives of the cubic spline through (x,y)[1..n];
 * yp1/ypn >= 1e30 signal natural (zero second derivative) ends. */
static void splinec(const double *x, const double *y, int n,
                    double yp1, double ypn, double *y2)
{
    double u[11];
    double qn, un;
    int i, k;

    if (yp1 > 0.99E30) {
        y2[1] = 0.0;
        u[1] = 0.0;
    } else {
        y2[1] = -0.5;
        u[1] = (3.0 / (x[2] - x[1])) * ((y[2] - y[1]) / (x[2] - x[1]) - yp1);
    }
    for (i = 2; i <= n - 1; i++) {
        double sig = (x[i] - x[i - 1]) / (x[i + 1] - x[i - 1]);
        double pp = sig * y2[i - 1] + 2.0;
        y2[i] = (sig - 1.0) / pp;
        u[i] = (6.0 * ((y[i + 1] - y[i]) / (x[i + 1] - x[i]) -
                       (y[i] - y[i - 1]) / (x[i] - x[i - 1])) /
                    (x[i + 1] - x[i - 1]) -
                sig * u[i - 1]) / pp;
    }
    if (ypn > 0.99E30) {
        qn = 0.0;
        un = 0.0;
    } else {
        qn = 0.5;
        un = (3.0 / (x[n] - x[n - 1])) *
             (ypn - (y[n] - y[n - 1]) / (x[n] - x[n - 1]));
    }
    y2[n] = (un - qn * u[n - 1]) / (qn * y2[n - 1] + 1.0);
    for (k = n - 1; k >= 1; k--)
        y2[k] = y2[k] * y2[k + 1] + u[k];
}

/* SPLINT: cubic spline interpolation at x. */
static double splintv(const double *xa, const double *ya, const double *y2a,
                      int n, double x)
{
    int klo = 1, khi = n;
    double h, a, b;
    while (khi - klo > 1) {
        int k = (khi + klo) / 2;
        if (xa[k] > x)
            khi = k;
        else
            klo = k;
    }
    h = xa[khi] - xa[klo];
    a = (xa[khi] - x) / h;
    b = (x - xa[klo]) / h;
    return a * ya[klo] + b * ya[khi] +
           ((a * a * a - a) * y2a[klo] + (b * b * b - b) * y2a[khi]) *
           h * h / 6.0;
}

/* SPLINI: integral of the cubic spline from xa[1] to x. */
static double spliniv(const double *xa, const double *ya, const double *y2a,
                      int n, double x)
{
    double yi = 0.0;
    int klo = 1, khi = 2;
    while (x > xa[klo] && khi <= n) {
        double xx = x;
        double h, a, b, a2, b2;
        if (khi < n && xa[khi] < x)
            xx = xa[khi];                       /* AMIN1(X, XA(KHI)) */
        h = xa[khi] - xa[klo];
        a = (xa[khi] - xx) / h;
        b = (xx - xa[klo]) / h;
        a2 = a * a;
        b2 = b * b;
        yi += ((1.0 - a2) * ya[klo] / 2.0 + b2 * ya[khi] / 2.0 +
               ((-(1.0 + a2 * a2) / 4.0 + a2 / 2.0) * y2a[klo] +
                (b2 * b2 / 4.0 - b2 / 2.0) * y2a[khi]) * h * h / 6.0) * h;
        klo++;
        khi++;
    }
    return yi;
}

/* DENSU: temperature and density profile for the thermosphere (Bates
 * profile above ZA, inverse-temperature cubic spline below). Writes
 * the temperature at alt into *tz; below ZA it also anchors
 * tn1[1]/tgn1[1] to the Bates profile, exactly like the Fortran
 * writing into the MESO7 common. */
static double densu(Msis *m, double alt, double dlb, double tinf, double tlb,
                    double xm, double alpha, double *tz, double zlb, double s2,
                    const double *zn1)
{
    double xs[6], ys[6], y2out[6];
    double densu_v, za, z, zg2, tt, ta;
    double t1 = 0.0, z1 = 0.0, x = 0.0, zgdif = 0.0;
    const int mn = 5;
    int k;

    za = zn1[1];
    z = (alt > za) ? alt : za;                    /* AMAX1(ALT,ZA)     */
    zg2 = zeta(m->re, z, zlb);
    tt = tinf - (tinf - tlb) * exp(-s2 * zg2);    /* Bates temperature */
    ta = tt;
    *tz = tt;
    densu_v = *tz;

    if (alt < za) {
        /* temperature below ZA: gradient at ZA from the Bates profile,
         * then inverse-temperature spline over the ZN1 nodes */
        double rr = (m->re + zlb) / (m->re + za);
        double dta = (tinf - ta) * s2 * rr * rr;
        double z2, t2, zg, yd1, yd2, y;
        m->tgn1[1] = dta;
        m->tn1[1] = ta;
        z = (alt > zn1[mn]) ? alt : zn1[mn];      /* AMAX1(ALT,ZN1(MN1)) */
        z1 = zn1[1];
        z2 = zn1[mn];
        t1 = m->tn1[1];
        t2 = m->tn1[mn];
        zg = zeta(m->re, z, z1);
        zgdif = zeta(m->re, z2, z1);
        for (k = 1; k <= mn; k++) {
            xs[k] = zeta(m->re, zn1[k], z1) / zgdif;
            ys[k] = 1.0 / m->tn1[k];
        }
        yd1 = -m->tgn1[1] / (t1 * t1) * zgdif;
        rr = (m->re + z2) / (m->re + z1);
        yd2 = -m->tgn1[2] / (t2 * t2) * zgdif * rr * rr;
        splinec(xs, ys, mn, yd1, yd2, y2out);
        x = zg / zgdif;
        y = splintv(xs, ys, y2out, mn, x);
        *tz = 1.0 / y;
        densu_v = *tz;
    }
    if (xm == 0.0)
        return densu_v;

    /* density above ZA */
    {
        double glb = m->gsurf / ((1.0 + zlb / m->re) * (1.0 + zlb / m->re));
        double gamma = xm * glb / (s2 * RGAS * tinf);
        double expl = exp(-s2 * gamma * zg2);
        if (expl > 50.0 || tt <= 0.0)
            expl = 50.0;
        densu_v = dlb * pow(tlb / tt, 1.0 + alpha + gamma) * expl;
    }
    if (alt >= za)
        return densu_v;

    /* density below ZA: spline-integrated temperature profile */
    {
        double glb = m->gsurf / ((1.0 + z1 / m->re) * (1.0 + z1 / m->re));
        double gamm = xm * glb * zgdif / RGAS;
        double yi = spliniv(xs, ys, y2out, mn, x);
        double expl = gamm * yi;
        if (expl > 50.0 || *tz <= 0.0)
            expl = 50.0;
        densu_v = densu_v * pow(t1 / *tz, 1.0 + alpha) * exp(-expl);
    }
    return densu_v;
}

/* DENSM: temperature and density profile for the lower atmosphere
 * (two chained inverse-temperature splines over the ZN2 and ZN3 node
 * grids). With xm == 0 returns the temperature instead. */
static double densm(Msis *m, double alt, double d0, double xm, double *tz)
{
    double xs[11], ys[11], y2out[11];
    double densm_v = d0;
    int k;

    if (alt <= ZN2_G[1]) {
        /* stratosphere / mesosphere */
        const int mn = 4;
        double z = (alt > ZN2_G[mn]) ? alt : ZN2_G[mn];
        double z1 = ZN2_G[1];
        double z2 = ZN2_G[mn];
        double t1 = m->tn2[1];
        double t2 = m->tn2[mn];
        double zg = zeta(m->re, z, z1);
        double zgdif = zeta(m->re, z2, z1);
        double yd1, yd2, x, y, rr;
        for (k = 1; k <= mn; k++) {
            xs[k] = zeta(m->re, ZN2_G[k], z1) / zgdif;
            ys[k] = 1.0 / m->tn2[k];
        }
        yd1 = -m->tgn2[1] / (t1 * t1) * zgdif;
        rr = (m->re + z2) / (m->re + z1);
        yd2 = -m->tgn2[2] / (t2 * t2) * zgdif * rr * rr;
        splinec(xs, ys, mn, yd1, yd2, y2out);
        x = zg / zgdif;
        y = splintv(xs, ys, y2out, mn, x);
        *tz = 1.0 / y;
        if (xm != 0.0) {
            double glb = m->gsurf / ((1.0 + z1 / m->re) * (1.0 + z1 / m->re));
            double gamm = xm * glb * zgdif / RGAS;
            double yi = spliniv(xs, ys, y2out, mn, x);
            double expl = gamm * yi;
            if (expl > 50.0)
                expl = 50.0;
            densm_v = densm_v * (t1 / *tz) * exp(-expl);
        }

        if (alt <= ZN3_G[1]) {
            /* troposphere / stratosphere */
            const int mn3 = 5;
            double z3 = alt;
            double z31 = ZN3_G[1];
            double z32 = ZN3_G[mn3];
            double t31 = m->tn3[1];
            double t32 = m->tn3[mn3];
            double zg3 = zeta(m->re, z3, z31);
            double zgdif3 = zeta(m->re, z32, z31);
            for (k = 1; k <= mn3; k++) {
                xs[k] = zeta(m->re, ZN3_G[k], z31) / zgdif3;
                ys[k] = 1.0 / m->tn3[k];
            }
            yd1 = -m->tgn3[1] / (t31 * t31) * zgdif3;
            rr = (m->re + z32) / (m->re + z31);
            yd2 = -m->tgn3[2] / (t32 * t32) * zgdif3 * rr * rr;
            splinec(xs, ys, mn3, yd1, yd2, y2out);
            x = zg3 / zgdif3;
            y = splintv(xs, ys, y2out, mn3, x);
            *tz = 1.0 / y;
            if (xm != 0.0) {
                double glb = m->gsurf / ((1.0 + z31 / m->re) * (1.0 + z31 / m->re));
                double gamm = xm * glb * zgdif3 / RGAS;
                double yi = spliniv(xs, ys, y2out, mn3, x);
                double expl = gamm * yi;
                if (expl > 50.0)
                    expl = 50.0;
                densm_v = densm_v * (t31 / *tz) * exp(-expl);
            }
        }
    }
    if (xm == 0.0)
        densm_v = *tz;
    return densm_v;
}

/* GLOBE7 statement function G0 (Eq. A24d). abs_p25 arrives already
 * clamped (Fortran patches P(25) in place; see file header). */
static double g0fn(double a, double abs_p25, double p26)
{
    return a - 4.0 + (p26 - 1.0) *
           (a - 4.0 + (exp(-abs_p25 * (a - 4.0)) - 1.0) / abs_p25);
}

/* GLOBE7 statement functions SG0/SUMEX (Eq. A24a/A24c): 3-hour Ap
 * history smoothing. Integer EX powers expanded to products. */
static double sg0fn(double ex, const double *ap, double abs_p25, double p26)
{
    double ex2 = ex * ex;
    double ex3 = ex2 * ex;
    double ex4 = ex2 * ex2;
    double ex8 = ex4 * ex4;
    double ex12 = ex8 * ex4;
    double ex19 = ex12 * ex4 * ex3;
    double sumex = 1.0 + (1.0 - ex19) / (1.0 - ex) * sqrt(ex);
    return (g0fn(ap[2], abs_p25, p26) +
            (g0fn(ap[3], abs_p25, p26) * ex +
             g0fn(ap[4], abs_p25, p26) * ex2 +
             g0fn(ap[5], abs_p25, p26) * ex3 +
             (g0fn(ap[6], abs_p25, p26) * ex4 +
              g0fn(ap[7], abs_p25, p26) * ex12) *
             (1.0 - ex8) / (1.0 - ex))) / sumex;
}

/* GLOBE7: G(L) function, upper-thermosphere horizontal/temporal
 * variations for the parameter column p. Also caches the Legendre
 * polynomials / local-time harmonics for the whole evaluation and
 * exports df, dfa, apdf, apt1 for glob7s. */
static double globe7(Msis *m, const double *p)
{
    double t[16];
    double cd14, cd18, cd32, cd39, f1, f2, tinf;
    int i, j;

    for (j = 1; j <= 14; j++)
        t[j] = 0.0;

    if (!m->plg_done) {
        /* Legendre polynomials (colatitude convention: c = sin(lat)) */
        double c = sin(m->glat * DGTR);
        double s = cos(m->glat * DGTR);
        double c2 = c * c;
        double c4 = c2 * c2;
        double s2 = s * s;
        PLG(2,1) = c;
        PLG(3,1) = 0.5 * (3.0 * c2 - 1.0);
        PLG(4,1) = 0.5 * (5.0 * c * c2 - 3.0 * c);
        PLG(5,1) = (35.0 * c4 - 30.0 * c2 + 3.0) / 8.0;
        PLG(6,1) = (63.0 * c2 * c2 * c - 70.0 * c2 * c + 15.0 * c) / 8.0;
        PLG(7,1) = (11.0 * c * PLG(6,1) - 5.0 * PLG(5,1)) / 6.0;
        PLG(2,2) = s;
        PLG(3,2) = 3.0 * c * s;
        PLG(4,2) = 1.5 * (5.0 * c2 - 1.0) * s;
        PLG(5,2) = 2.5 * (7.0 * c2 * c - 3.0 * c) * s;
        PLG(6,2) = 1.875 * (21.0 * c4 - 14.0 * c2 + 1.0) * s;
        PLG(7,2) = (11.0 * c * PLG(6,2) - 6.0 * PLG(5,2)) / 5.0;
        PLG(3,3) = 3.0 * s2;
        PLG(4,3) = 15.0 * s2 * c;
        PLG(5,3) = 7.5 * (7.0 * c2 - 1.0) * s2;
        PLG(6,3) = 3.0 * c * PLG(5,3) - 2.0 * PLG(4,3);
        PLG(7,3) = (11.0 * c * PLG(6,3) - 7.0 * PLG(5,3)) / 4.0;
        PLG(8,3) = (13.0 * c * PLG(7,3) - 8.0 * PLG(6,3)) / 5.0;
        PLG(4,4) = 15.0 * s2 * s;
        PLG(5,4) = 105.0 * s2 * s * c;
        PLG(6,4) = (9.0 * c * PLG(5,4) - 7.0 * PLG(4,4)) / 2.0;
        PLG(7,4) = (11.0 * c * PLG(6,4) - 8.0 * PLG(5,4)) / 3.0;
        m->plg_done = 1;
    }
    if (!m->tloc_done) {
        m->stloc = sin(HR * m->tloc);
        m->ctloc = cos(HR * m->tloc);
        m->s2tloc = sin(2.0 * HR * m->tloc);
        m->c2tloc = cos(2.0 * HR * m->tloc);
        m->s3tloc = sin(3.0 * HR * m->tloc);
        m->c3tloc = cos(3.0 * HR * m->tloc);
        m->tloc_done = 1;
    }

    cd14 = cos(DR * (m->day - P(14)));
    cd18 = cos(2.0 * DR * (m->day - P(18)));
    cd32 = cos(DR * (m->day - P(32)));
    cd39 = cos(2.0 * DR * (m->day - P(39)));

    /* F10.7 effect */
    m->df = m->f107 - m->f107a;
    m->dfa = m->f107a - 150.0;
    t[1] = P(20) * m->df * (1.0 + P(60) * m->dfa) + P(21) * m->df * m->df +
           P(22) * m->dfa + P(30) * m->dfa * m->dfa;
    f1 = 1.0 + (P(48) * m->dfa + P(20) * m->df + P(21) * m->df * m->df) * SWC(1);
    f2 = 1.0 + (P(50) * m->dfa + P(20) * m->df + P(21) * m->df * m->df) * SWC(1);

    /* time independent */
    t[2] = (P(2) * PLG(3,1) + P(3) * PLG(5,1) + P(23) * PLG(7,1)) +
           (P(15) * PLG(3,1)) * m->dfa * SWC(1) + P(27) * PLG(2,1);
    /* symmetrical annual */
    t[3] = P(19) * cd32;
    /* symmetrical semiannual */
    t[4] = (P(16) + P(17) * PLG(3,1)) * cd18;
    /* asymmetrical annual */
    t[5] = f1 * (P(10) * PLG(2,1) + P(11) * PLG(4,1)) * cd14;
    /* asymmetrical semiannual */
    t[6] = P(38) * PLG(2,1) * cd39;
    /* diurnal */
    {
        double t71 = (P(12) * PLG(3,2)) * cd14 * SWC(5);
        double t72 = (P(13) * PLG(3,2)) * cd14 * SWC(5);
        t[7] = f2 *
               ((P(4) * PLG(2,2) + P(5) * PLG(4,2) + P(28) * PLG(6,2) + t71) *
                m->ctloc +
                (P(7) * PLG(2,2) + P(8) * PLG(4,2) + P(29) * PLG(6,2) + t72) *
                m->stloc);
    }
    /* semidiurnal */
    {
        double t81 = (P(24) * PLG(4,3) + P(36) * PLG(6,3)) * cd14 * SWC(5);
        double t82 = (P(34) * PLG(4,3) + P(37) * PLG(6,3)) * cd14 * SWC(5);
        t[8] = f2 * ((P(6) * PLG(3,3) + P(42) * PLG(5,3) + t81) * m->c2tloc +
                     (P(9) * PLG(3,3) + P(43) * PLG(5,3) + t82) * m->s2tloc);
    }
    /* terdiurnal */
    t[14] = f2 *
            ((P(40) * PLG(4,4) +
              (P(94) * PLG(5,4) + P(47) * PLG(7,4)) * cd14 * SWC(5)) * m->s3tloc +
             (P(41) * PLG(4,4) +
              (P(95) * PLG(5,4) + P(49) * PLG(7,4)) * cd14 * SWC(5)) * m->c3tloc);

    /* magnetic activity */
    if (m->sw9 == -1.0) {
        /* 3-hour Ap history (Eqs. A24a-d) */
        if (P(52) != 0.0) {
            double exp1 = exp(-10800.0 * fabs(P(52)) /
                              (1.0 + P(139) * (45.0 - fabs(m->glat))));
            double p25c = P(25);
            if (exp1 > 0.99999)
                exp1 = 0.99999;
            if (p25c < 1.0E-4)
                p25c = 1.0E-4;
            m->apt1 = sg0fn(exp1, m->ap, p25c, P(26));
            t[9] = m->apt1 *
                   (P(51) + P(97) * PLG(3,1) + P(55) * PLG(5,1) +
                    (P(126) * PLG(2,1) + P(127) * PLG(4,1) + P(128) * PLG(6,1)) *
                    cd14 * SWC(5) +
                    (P(129) * PLG(2,2) + P(130) * PLG(4,2) + P(131) * PLG(6,2)) *
                    SWC(7) * cos(HR * (m->tloc - P(132))));
        }
    } else {
        /* daily Ap */
        double apd = m->ap[1] - 4.0;
        double p44 = P(44);
        double p45 = P(45);
        if (p44 < 0.0)
            p44 = 1.0E-5;
        m->apdf = apd + (p45 - 1.0) * (apd + (exp(-p44 * apd) - 1.0) / p44);
        t[9] = m->apdf *
               (P(33) + P(46) * PLG(3,1) + P(35) * PLG(5,1) +
                (P(101) * PLG(2,1) + P(102) * PLG(4,1) + P(103) * PLG(6,1)) *
                cd14 * SWC(5) +
                (P(122) * PLG(2,2) + P(123) * PLG(4,2) + P(124) * PLG(6,2)) *
                SWC(7) * cos(HR * (m->tloc - P(125))));
    }

    if (m->glon > -1000.0) {
        /* longitudinal */
        t[11] = (1.0 + P(81) * m->dfa * SWC(1)) *
                ((P(65) * PLG(3,2) + P(66) * PLG(5,2) + P(67) * PLG(7,2) +
                  P(104) * PLG(2,2) + P(105) * PLG(4,2) + P(106) * PLG(6,2) +
                  SWC(5) * (P(110) * PLG(2,2) + P(111) * PLG(4,2) +
                            P(112) * PLG(6,2)) * cd14) *
                 cos(DGTR * m->glon) +
                 (P(91) * PLG(3,2) + P(92) * PLG(5,2) + P(93) * PLG(7,2) +
                  P(107) * PLG(2,2) + P(108) * PLG(4,2) + P(109) * PLG(6,2) +
                  SWC(5) * (P(113) * PLG(2,2) + P(114) * PLG(4,2) +
                            P(115) * PLG(6,2)) * cd14) *
                 sin(DGTR * m->glon));
        /* UT and mixed UT/longitude */
        t[12] = (1.0 + P(96) * PLG(2,1)) * (1.0 + P(82) * m->dfa * SWC(1)) *
                (1.0 + P(120) * PLG(2,1) * SWC(5) * cd14) *
                ((P(69) * PLG(2,1) + P(70) * PLG(4,1) + P(71) * PLG(6,1)) *
                 cos(SR * (m->sec - P(72))));
        t[12] += SWC(11) *
                 (P(77) * PLG(4,3) + P(78) * PLG(6,3) + P(79) * PLG(8,3)) *
                 cos(SR * (m->sec - P(80)) + 2.0 * DGTR * m->glon) *
                 (1.0 + P(138) * m->dfa * SWC(1));
        /* UT/longitude magnetic activity */
        if (m->sw9 == -1.0) {
            if (P(52) != 0.0) {
                t[13] = m->apt1 * SWC(11) * (1.0 + P(133) * PLG(2,1)) *
                        ((P(53) * PLG(3,2) + P(99) * PLG(5,2) + P(68) * PLG(7,2)) *
                         cos(DGTR * (m->glon - P(98)))) +
                        m->apt1 * SWC(11) * SWC(5) *
                        (P(134) * PLG(2,2) + P(135) * PLG(4,2) + P(136) * PLG(6,2)) *
                        cd14 * cos(DGTR * (m->glon - P(137))) +
                        m->apt1 * SWC(12) *
                        (P(56) * PLG(2,1) + P(57) * PLG(4,1) + P(58) * PLG(6,1)) *
                        cos(SR * (m->sec - P(59)));
            }
        } else {
            t[13] = m->apdf * SWC(11) * (1.0 + P(121) * PLG(2,1)) *
                    ((P(61) * PLG(3,2) + P(62) * PLG(5,2) + P(63) * PLG(7,2)) *
                     cos(DGTR * (m->glon - P(64)))) +
                    m->apdf * SWC(11) * SWC(5) *
                    (P(116) * PLG(2,2) + P(117) * PLG(4,2) + P(118) * PLG(6,2)) *
                    cd14 * cos(DGTR * (m->glon - P(119))) +
                    m->apdf * SWC(12) *
                    (P(84) * PLG(2,1) + P(85) * PLG(4,1) + P(86) * PLG(6,1)) *
                    cos(SR * (m->sec - P(76)));
        }
    }

    tinf = P(31);
    for (i = 1; i <= 14; i++)
        tinf += fabs(SW(i)) * t[i];
    return tinf;
}

/* GLOB7S: version of GLOBE7 for the lower atmosphere (uses the
 * Legendre/local-time cache and the df/apdf/apt1 exports of the last
 * globe7 call, which the evaluation order guarantees has run). The
 * Fortran's P(100) parameter-set stamp/guard is meaningless with
 * const tables and was dropped. */
static double glob7s(Msis *m, const double *p)
{
    double t[16];
    double cd14, cd18, cd32, cd39, tt;
    int i, j;

    for (j = 1; j <= 14; j++)
        t[j] = 0.0;
    cd32 = cos(DR * (m->day - P(32)));
    cd18 = cos(2.0 * DR * (m->day - P(18)));
    cd14 = cos(DR * (m->day - P(14)));
    cd39 = cos(2.0 * DR * (m->day - P(39)));

    /* F10.7 */
    t[1] = P(22) * m->dfa;
    /* time independent */
    t[2] = P(2) * PLG(3,1) + P(3) * PLG(5,1) + P(23) * PLG(7,1) +
           P(27) * PLG(2,1) + P(15) * PLG(4,1) + P(60) * PLG(6,1);
    /* symmetrical annual */
    t[3] = (P(19) + P(48) * PLG(3,1) + P(30) * PLG(5,1)) * cd32;
    /* symmetrical semiannual */
    t[4] = (P(16) + P(17) * PLG(3,1) + P(31) * PLG(5,1)) * cd18;
    /* asymmetrical annual */
    t[5] = (P(10) * PLG(2,1) + P(11) * PLG(4,1) + P(21) * PLG(6,1)) * cd14;
    /* asymmetrical semiannual */
    t[6] = (P(38) * PLG(2,1)) * cd39;
    /* diurnal */
    {
        double t71 = P(12) * PLG(3,2) * cd14 * SWC(5);
        double t72 = P(13) * PLG(3,2) * cd14 * SWC(5);
        t[7] = (P(4) * PLG(2,2) + P(5) * PLG(4,2) + t71) * m->ctloc +
               (P(7) * PLG(2,2) + P(8) * PLG(4,2) + t72) * m->stloc;
    }
    /* semidiurnal */
    {
        double t81 = (P(24) * PLG(4,3) + P(36) * PLG(6,3)) * cd14 * SWC(5);
        double t82 = (P(34) * PLG(4,3) + P(37) * PLG(6,3)) * cd14 * SWC(5);
        t[8] = (P(6) * PLG(3,3) + P(42) * PLG(5,3) + t81) * m->c2tloc +
               (P(9) * PLG(3,3) + P(43) * PLG(5,3) + t82) * m->s2tloc;
    }
    /* terdiurnal */
    t[14] = P(40) * PLG(4,4) * m->s3tloc + P(41) * PLG(4,4) * m->c3tloc;

    /* magnetic activity */
    if (m->sw9 == 1.0)
        t[9] = m->apdf * (P(33) + P(46) * PLG(3,1) * SWC(2));
    if (m->sw9 == -1.0)
        t[9] = P(51) * m->apt1 + P(97) * PLG(3,1) * m->apt1 * SWC(2);

    /* longitudinal */
    if (m->glon > -1000.0) {
        t[11] = (1.0 +
                 PLG(2,1) * (P(81) * SWC(5) * cos(DR * (m->day - P(82))) +
                             P(86) * SWC(6) * cos(2.0 * DR * (m->day - P(87)))) +
                 P(84) * SWC(3) * cos(DR * (m->day - P(85))) +
                 P(88) * SWC(4) * cos(2.0 * DR * (m->day - P(89)))) *
                ((P(65) * PLG(3,2) + P(66) * PLG(5,2) + P(67) * PLG(7,2) +
                  P(75) * PLG(2,2) + P(76) * PLG(4,2) + P(77) * PLG(6,2)) *
                 cos(DGTR * m->glon) +
                 (P(91) * PLG(3,2) + P(92) * PLG(5,2) + P(93) * PLG(7,2) +
                  P(78) * PLG(2,2) + P(79) * PLG(4,2) + P(80) * PLG(6,2)) *
                 sin(DGTR * m->glon));
    }

    tt = 0.0;
    for (i = 1; i <= 14; i++)
        tt += fabs(SW(i)) * t[i];
    return tt;
}

/* GTS7: thermospheric portion (alt >= 72.5 km), MASS=48 path.
 * n2_only reproduces GTD7's internal MSS=28 call for the fully mixed
 * region (alt < ZMIX): only the N2 profile is evaluated. d/t are
 * 1-based views (d[1..9], t[1..2]), native CGS units. */
static void gts7(Msis *m, double alt, int n2_only, double *d, double *t)
{
    double zn1[6];
    double tinf, g28, zhf, xmm, z;
    double b28, zh28, zhm28, xmd;
    double tz = 0.0;
    int j;

    zn1[0] = 0.0;
    zn1[1] = PDL(16,2);        /* ZA: joining altitude of Bates and spline */
    zn1[2] = 110.0;
    zn1[3] = 100.0;
    zn1[4] = 90.0;
    zn1[5] = 72.5;

    for (j = 1; j <= 9; j++)
        d[j] = 0.0;

    /* exospheric temperature: TINF variations matter above ZN1(1) only */
    if (alt > zn1[1])
        tinf = PTM(1) * PT(1) * (1.0 + SW(16) * globe7(m, msis_pt));
    else
        tinf = PTM(1) * PT(1);
    t[1] = tinf;

    /* temperature gradient: variations matter above ZN1(5) only */
    if (alt > zn1[5])
        m->g0 = PTM(4) * PS(1) * (1.0 + SW(19) * globe7(m, msis_ps));
    else
        m->g0 = PTM(4) * PS(1);

    m->tlb = PTM(2) * (1.0 + SW(17) * globe7(m, msis_pd[3])) * PD(1,4);
    m->s = m->g0 / (tinf - m->tlb);

    /* lower-thermosphere temperature nodes; their variations are not
     * significant for density above 300 km */
    if (alt < 300.0) {
        m->tn1[2] = PTM(7) * PTL(1,1) / (1.0 - SW(18) * glob7s(m, msis_ptl[0]));
        m->tn1[3] = PTM(3) * PTL(1,2) / (1.0 - SW(18) * glob7s(m, msis_ptl[1]));
        m->tn1[4] = PTM(8) * PTL(1,3) / (1.0 - SW(18) * glob7s(m, msis_ptl[2]));
        m->tn1[5] = PTM(5) * PTL(1,4) /
                    (1.0 - SW(18) * SW(20) * glob7s(m, msis_ptl[3]));
        m->tgn1[2] = PTM(9) * PMA(1,9) *
                     (1.0 + SW(18) * SW(20) * glob7s(m, msis_pma[8])) *
                     m->tn1[5] * m->tn1[5] /
                     ((PTM(5) * PTL(1,4)) * (PTM(5) * PTL(1,4)));
    } else {
        m->tn1[2] = PTM(7) * PTL(1,1);
        m->tn1[3] = PTM(3) * PTL(1,2);
        m->tn1[4] = PTM(8) * PTL(1,3);
        m->tn1[5] = PTM(5) * PTL(1,4);
        m->tgn1[2] = PTM(9) * PMA(1,9) * m->tn1[5] * m->tn1[5] /
                     ((PTM(5) * PTL(1,4)) * (PTM(5) * PTL(1,4)));
    }

    /* N2 variation factor at Zlb */
    g28 = SW(21) * globe7(m, msis_pd[2]);

    /* variation of turbopause height */
    zhf = PDL(25,2) * (1.0 + SW(5) * PDL(25,1) * sin(DGTR * m->glat) *
                             cos(DR * (m->day - PT(14))));
    xmm = PDM(5,3);
    z = alt;

    /* **** N2 density **** */
    m->db28 = PDM(1,3) * exp(g28) * PD(1,3);
    d[3] = densu(m, z, m->db28, tinf, m->tlb, 28.0, ALPHA(3), &t[2],
                 PTM(6), m->s, zn1);
    m->dd = d[3];
    zh28 = PDM(3,3) * zhf;                     /* turbopause             */
    zhm28 = PDM(4,3) * PDL(6,2);
    xmd = 28.0 - xmm;
    b28 = densu(m, zh28, m->db28, tinf, m->tlb, xmd, ALPHA(3) - 1.0, &tz,
                PTM(6), m->s, zn1);            /* mixed density at Zlb   */
    if (!(z > ALTL(3) || SW(15) == 0.0)) {
        m->dm28 = densu(m, z, b28, tinf, m->tlb, xmm, ALPHA(3), &tz,
                        PTM(6), m->s, zn1);    /* mixed density at Alt   */
        d[3] = dnet(d[3], m->dm28, zhm28, xmm, 28.0);
    }
    if (n2_only)
        return;

    /* **** He density **** */
    {
        double g4 = SW(21) * globe7(m, msis_pd[0]);
        m->db04 = PDM(1,1) * exp(g4) * PD(1,1);
        d[1] = densu(m, z, m->db04, tinf, m->tlb, 4.0, ALPHA(1), &t[2],
                     PTM(6), m->s, zn1);
        m->dd = d[1];
        if (!(z > ALTL(1) || SW(15) == 0.0)) {
            double zh04 = PDM(3,1);
            double b04 = densu(m, zh04, m->db04, tinf, m->tlb, 4.0 - xmm,
                               ALPHA(1) - 1.0, &t[2], PTM(6), m->s, zn1);
            double zhm04 = zhm28;
            double zc04, hc04;
            m->dm04 = densu(m, z, b04, tinf, m->tlb, xmm, 0.0, &t[2],
                            PTM(6), m->s, zn1);
            d[1] = dnet(d[1], m->dm04, zhm04, xmm, 4.0);
            /* correction to specified mixing ratio at ground */
            m->rl = log(b28 * PDM(2,1) / b04);
            zc04 = PDM(5,1) * PDL(1,2);
            hc04 = PDM(6,1) * PDL(2,2);
            d[1] = d[1] * ccor(z, m->rl, hc04, zc04);
        }
    }

    /* **** O density **** */
    {
        double g16 = SW(21) * globe7(m, msis_pd[1]);
        m->db16 = PDM(1,2) * exp(g16) * PD(1,2);
        d[2] = densu(m, z, m->db16, tinf, m->tlb, 16.0, ALPHA(2), &t[2],
                     PTM(6), m->s, zn1);
        m->dd = d[2];
        if (!(z > ALTL(2) || SW(15) == 0.0)) {
            double zh16 = PDM(3,2);
            double b16 = densu(m, zh16, m->db16, tinf, m->tlb, 16.0 - xmm,
                               ALPHA(2) - 1.0, &t[2], PTM(6), m->s, zn1);
            double zhm16 = zhm28;
            double hc16, zc16, hc216, hcc16, zcc16, rc16;
            m->dm16 = densu(m, z, b16, tinf, m->tlb, xmm, 0.0, &t[2],
                            PTM(6), m->s, zn1);
            d[2] = dnet(d[2], m->dm16, zhm16, xmm, 16.0);
            /* 3/16/99: O departure from diffusive equilibrium near
             * 150 km + dependence on F10.7 */
            m->rl = PDM(2,2) * PDL(17,2) *
                    (1.0 + SW(1) * PDL(24,1) * (m->f107a - 150.0));
            hc16 = PDM(6,2) * PDL(4,2);
            zc16 = PDM(5,2) * PDL(3,2);
            hc216 = PDM(6,2) * PDL(5,2);
            d[2] = d[2] * ccor2(z, m->rl, hc16, zc16, hc216);
            /* chemistry correction */
            hcc16 = PDM(8,2) * PDL(14,2);
            zcc16 = PDM(7,2) * PDL(13,2);
            rc16 = PDM(4,2) * PDL(15,2);
            d[2] = d[2] * ccor(z, rc16, hcc16, zcc16);
        }
    }

    /* **** O2 density **** */
    {
        double g32 = SW(21) * globe7(m, msis_pd[4]);
        m->db32 = PDM(1,4) * exp(g32) * PD(1,5);
        d[4] = densu(m, z, m->db32, tinf, m->tlb, 32.0, ALPHA(4), &t[2],
                     PTM(6), m->s, zn1);
        m->dd = d[4];
        if (SW(15) != 0.0) {
            if (z <= ALTL(4)) {
                double zh32 = PDM(3,4);
                double b32 = densu(m, zh32, m->db32, tinf, m->tlb, 32.0 - xmm,
                                   ALPHA(4) - 1.0, &t[2], PTM(6), m->s, zn1);
                double zhm32 = zhm28;
                double hc32, zc32;
                m->dm32 = densu(m, z, b32, tinf, m->tlb, xmm, 0.0, &t[2],
                                PTM(6), m->s, zn1);
                d[4] = dnet(d[4], m->dm32, zhm32, xmm, 32.0);
                /* correction to specified mixing ratio at ground */
                m->rl = log(b28 * PDM(2,4) / b32);
                hc32 = PDM(6,4) * PDL(8,2);
                zc32 = PDM(5,4) * PDL(7,2);
                d[4] = d[4] * ccor(z, m->rl, hc32, zc32);
            }
            /* correction for general departure from diffusive
             * equilibrium above Zlb (applies at every altitude) */
            {
                double hcc32 = PDM(8,4) * PDL(23,2);
                double hcc232 = PDM(8,4) * PDL(23,1);
                double zcc32 = PDM(7,4) * PDL(22,2);
                double rc32 = PDM(4,4) * PDL(24,2) *
                              (1.0 + SW(1) * PDL(24,1) * (m->f107a - 150.0));
                d[4] = d[4] * ccor2(z, rc32, hcc32, zcc32, hcc232);
            }
        }
    }

    /* **** Ar density **** */
    {
        double g40 = SW(21) * globe7(m, msis_pd[5]);
        m->db40 = PDM(1,5) * exp(g40) * PD(1,6);
        d[5] = densu(m, z, m->db40, tinf, m->tlb, 40.0, ALPHA(5), &t[2],
                     PTM(6), m->s, zn1);
        m->dd = d[5];
        if (!(z > ALTL(5) || SW(15) == 0.0)) {
            double zh40 = PDM(3,5);
            double b40 = densu(m, zh40, m->db40, tinf, m->tlb, 40.0 - xmm,
                               ALPHA(5) - 1.0, &t[2], PTM(6), m->s, zn1);
            double zhm40 = zhm28;
            double hc40, zc40;
            m->dm40 = densu(m, z, b40, tinf, m->tlb, xmm, 0.0, &t[2],
                            PTM(6), m->s, zn1);
            d[5] = dnet(d[5], m->dm40, zhm40, xmm, 40.0);
            /* correction to specified mixing ratio at ground */
            m->rl = log(b28 * PDM(2,5) / b40);
            hc40 = PDM(6,5) * PDL(10,2);
            zc40 = PDM(5,5) * PDL(9,2);
            d[5] = d[5] * ccor(z, m->rl, hc40, zc40);
        }
    }

    /* **** hydrogen density **** */
    {
        double g1 = SW(21) * globe7(m, msis_pd[6]);
        m->db01 = PDM(1,6) * exp(g1) * PD(1,7);
        d[7] = densu(m, z, m->db01, tinf, m->tlb, 1.0, ALPHA(7), &t[2],
                     PTM(6), m->s, zn1);
        m->dd = d[7];
        if (!(z > ALTL(7) || SW(15) == 0.0)) {
            double zh01 = PDM(3,6);
            double b01 = densu(m, zh01, m->db01, tinf, m->tlb, 1.0 - xmm,
                               ALPHA(7) - 1.0, &t[2], PTM(6), m->s, zn1);
            double zhm01 = zhm28;
            double hc01, zc01, hcc01, zcc01, rc01;
            m->dm01 = densu(m, z, b01, tinf, m->tlb, xmm, 0.0, &t[2],
                            PTM(6), m->s, zn1);
            d[7] = dnet(d[7], m->dm01, zhm01, xmm, 1.0);
            /* correction to specified mixing ratio at ground */
            m->rl = log(b28 * PDM(2,6) * fabs(PDL(18,2)) / b01);
            hc01 = PDM(6,6) * PDL(12,2);
            zc01 = PDM(5,6) * PDL(11,2);
            d[7] = d[7] * ccor(z, m->rl, hc01, zc01);
            /* chemistry correction */
            hcc01 = PDM(8,6) * PDL(20,2);
            zcc01 = PDM(7,6) * PDL(19,2);
            rc01 = PDM(4,6) * PDL(21,2);
            d[7] = d[7] * ccor(z, rc01, hcc01, zcc01);
        }
    }

    /* **** atomic nitrogen density **** */
    {
        double g14 = SW(21) * globe7(m, msis_pd[7]);
        m->db14 = PDM(1,7) * exp(g14) * PD(1,8);
        d[8] = densu(m, z, m->db14, tinf, m->tlb, 14.0, ALPHA(8), &t[2],
                     PTM(6), m->s, zn1);
        m->dd = d[8];
        if (!(z > ALTL(8) || SW(15) == 0.0)) {
            double zh14 = PDM(3,7);
            double b14 = densu(m, zh14, m->db14, tinf, m->tlb, 14.0 - xmm,
                               ALPHA(8) - 1.0, &t[2], PTM(6), m->s, zn1);
            double zhm14 = zhm28;
            double hc14, zc14, hcc14, zcc14, rc14;
            m->dm14 = densu(m, z, b14, tinf, m->tlb, xmm, 0.0, &t[2],
                            PTM(6), m->s, zn1);
            d[8] = dnet(d[8], m->dm14, zhm14, xmm, 14.0);
            /* correction to specified mixing ratio at ground */
            m->rl = log(b28 * PDM(2,7) * fabs(PDL(3,1)) / b14);
            hc14 = PDM(6,7) * PDL(2,1);
            zc14 = PDM(5,7) * PDL(1,1);
            d[8] = d[8] * ccor(z, m->rl, hc14, zc14);
            /* chemistry correction */
            hcc14 = PDM(8,7) * PDL(5,1);
            zcc14 = PDM(7,7) * PDL(4,1);
            rc14 = PDM(4,7) * PDL(6,1);
            d[8] = d[8] * ccor(z, rc14, hcc14, zcc14);
        }
    }

    /* **** anomalous oxygen density **** */
    {
        double g16h = SW(21) * globe7(m, msis_pd[8]);
        double db16h = PDM(1,8) * exp(g16h) * PD(1,9);
        double tho = PDM(10,8) * PDL(7,1);
        double t2dum;    /* Fortran writes the undeclared T2, not T(2) */
        double zsht, zmho, zsho;
        m->dd = densu(m, z, db16h, tho, tho, 16.0, ALPHA(9), &t2dum,
                      PTM(6), m->s, zn1);
        zsht = PDM(6,8);
        zmho = PDM(5,8);
        zsho = scalh(m, zmho, 16.0, tho);
        d[9] = m->dd * exp(-zsht / zsho * (exp(-(z - zmho) / zsht) - 1.0));
    }

    /* total mass density (anomalous O NOT included -- GTD7 convention) */
    d[6] = 1.66E-24 * (4.0 * d[1] + 16.0 * d[2] + 28.0 * d[3] +
                       32.0 * d[4] + 40.0 * d[5] + d[7] + 14.0 * d[8]);
    m->db48 = 1.66E-24 * (4.0 * m->db04 + 16.0 * m->db16 + 28.0 * m->db28 +
                          32.0 * m->db32 + 40.0 * m->db40 + m->db01 +
                          14.0 * m->db14);
}

/* GTD7 core: thermosphere via gts7, lower atmosphere via the
 * ZN2/ZN3 temperature-node splines and mixing-ratio scaling. */
static void gtd7core(Msis *m, double alt, double *d, double *t)
{
    double ds[10], ts[3];
    double dm28m, xmm, altt, dmc, dz28, dmr;
    double tz = 0.0;
    int n2_only, j;

    for (j = 0; j <= 9; j++)
        ds[j] = 0.0;
    ts[0] = ts[1] = ts[2] = 0.0;

    /* latitude variation of gravity */
    glatf(m->glat, &m->gsurf, &m->re);

    xmm = PDM(5,3);

    /* thermosphere / mesosphere (above ZN2(1)) */
    altt = (alt > ZN2_G[1]) ? alt : ZN2_G[1];
    n2_only = (alt < ZMIX);   /* GTD7's MSS=28 call in the mixed region */
    gts7(m, altt, n2_only, ds, ts);
    dm28m = m->dm28;          /* native CGS units (Fortran IMR=0)       */
    t[1] = ts[1];
    t[2] = ts[2];
    if (alt >= ZN2_G[1]) {
        for (j = 1; j <= 9; j++)
            d[j] = ds[j];
        return;
    }

    /* lower mesosphere / upper stratosphere (ZN3(1)..ZN2(1)):
     * temperature at nodes and gradients at end nodes; inverse
     * temperature a linear function of spherical harmonics */
    m->tgn2[1] = m->tgn1[2];
    m->tn2[1] = m->tn1[5];
    m->tn2[2] = PMA(1,1) * PAVGM(1) / (1.0 - SW(20) * glob7s(m, msis_pma[0]));
    m->tn2[3] = PMA(1,2) * PAVGM(2) / (1.0 - SW(20) * glob7s(m, msis_pma[1]));
    m->tn2[4] = PMA(1,3) * PAVGM(3) /
                (1.0 - SW(20) * SW(22) * glob7s(m, msis_pma[2]));
    m->tgn2[2] = PAVGM(9) * PMA(1,10) *
                 (1.0 + SW(20) * SW(22) * glob7s(m, msis_pma[9])) *
                 m->tn2[4] * m->tn2[4] /
                 ((PMA(1,3) * PAVGM(3)) * (PMA(1,3) * PAVGM(3)));
    m->tn3[1] = m->tn2[4];

    if (alt < ZN3_G[1]) {
        /* lower stratosphere and troposphere (below ZN3(1)) */
        m->tgn3[1] = m->tgn2[2];
        m->tn3[2] = PMA(1,4) * PAVGM(4) / (1.0 - SW(22) * glob7s(m, msis_pma[3]));
        m->tn3[3] = PMA(1,5) * PAVGM(5) / (1.0 - SW(22) * glob7s(m, msis_pma[4]));
        m->tn3[4] = PMA(1,6) * PAVGM(6) / (1.0 - SW(22) * glob7s(m, msis_pma[5]));
        m->tn3[5] = PMA(1,7) * PAVGM(7) / (1.0 - SW(22) * glob7s(m, msis_pma[6]));
        m->tgn3[2] = PMA(1,8) * PAVGM(8) *
                     (1.0 + SW(22) * glob7s(m, msis_pma[7])) *
                     m->tn3[5] * m->tn3[5] /
                     ((PMA(1,7) * PAVGM(7)) * (PMA(1,7) * PAVGM(7)));
    }

    /* linear transition to full mixing below ZN2(1) */
    dmc = 0.0;
    if (alt > ZMIX)
        dmc = 1.0 - (ZN2_G[1] - alt) / (ZN2_G[1] - ZMIX);
    dz28 = ds[3];

    /* N2 density */
    dmr = ds[3] / dm28m - 1.0;
    d[3] = densm(m, alt, dm28m, xmm, &tz);
    d[3] = d[3] * (1.0 + dmr * dmc);
    /* He density */
    dmr = ds[1] / (dz28 * PDM(2,1)) - 1.0;
    d[1] = d[3] * PDM(2,1) * (1.0 + dmr * dmc);
    /* O and anomalous O: zero below 72.5 km */
    d[2] = 0.0;
    d[9] = 0.0;
    /* O2 density */
    dmr = ds[4] / (dz28 * PDM(2,4)) - 1.0;
    d[4] = d[3] * PDM(2,4) * (1.0 + dmr * dmc);
    /* Ar density */
    dmr = ds[5] / (dz28 * PDM(2,5)) - 1.0;
    d[5] = d[3] * PDM(2,5) * (1.0 + dmr * dmc);
    /* H and atomic N: zero below 72.5 km */
    d[7] = 0.0;
    d[8] = 0.0;

    /* total mass density */
    d[6] = 1.66E-24 * (4.0 * d[1] + 16.0 * d[2] + 28.0 * d[3] +
                       32.0 * d[4] + 40.0 * d[5] + d[7] + 14.0 * d[8]);
    t[2] = tz;
}

/* Bind the input struct onto a zeroed scratch. */
static void msis_setup(Msis *m, const SpodyNrlmsise00Input *inp)
{
    memset(m, 0, sizeof *m);
    m->day = (double)(inp->doy % 1000);   /* Fortran AMOD(YRD,1000.)   */
    m->sec = inp->sec;
    m->glat = inp->glat_deg;
    m->glon = inp->glon_deg;
    m->tloc = inp->lst_hr;
    m->f107a = inp->f107a;
    m->f107 = inp->f107;
    if (inp->use_ap_array) {
        int i;
        m->sw9 = -1.0;
        for (i = 0; i < 7; i++)
            m->ap[i + 1] = inp->ap_array[i];
    } else {
        m->sw9 = 1.0;
        m->ap[1] = inp->ap;
    }
}

void spody_nrlmsise00_gtd7(const SpodyNrlmsise00Input *inp,
                           SpodyNrlmsise00Output *out)
{
    Msis m;
    double d[10], t[3];
    int j;

    msis_setup(&m, inp);
    gtd7core(&m, inp->alt_km, d, t);
    for (j = 1; j <= 9; j++)
        out->d[j - 1] = d[j];
    out->t[0] = t[1];
    out->t[1] = t[2];
}

void spody_nrlmsise00_gtd7d(const SpodyNrlmsise00Input *inp,
                            SpodyNrlmsise00Output *out)
{
    spody_nrlmsise00_gtd7(inp, out);
    /* effective total mass density for drag: add anomalous oxygen */
    out->d[5] = 1.66E-24 * (4.0 * out->d[0] + 16.0 * out->d[1] +
                            28.0 * out->d[2] + 32.0 * out->d[3] +
                            40.0 * out->d[4] + out->d[6] +
                            14.0 * out->d[7] + 16.0 * out->d[8]);
}
