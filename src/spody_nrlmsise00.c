/*
 * spody_nrlmsise00.c -- NRLMSISE-00, C port of the official NRL Fortran.
 *
 * See spody_nrlmsise00.h for provenance, scope and units. Translation
 * rules used throughout this file (they are what makes the port
 * reviewable line-by-line against NRLMSISE-00.FOR):
 *
 *   - Parameter tables keep the Fortran 1-based, column-major access
 *     notation via the P()/PD()/PDL()/... macros below, so an
 *     expression like PDM(5,3) here IS Fortran's PDM(5,3).
 *   - Function-local working arrays that mirror Fortran arrays are
 *     allocated one slot larger and indexed 1-based for the same
 *     reason (d[1..9], t[1..2], tn1[1..5], plg(i,j), spline nodes).
 *   - Every COMMON block became a field group of the stack-allocated
 *     `Msis` scratch struct: the model is re-entrant by construction
 *     and safe for concurrent OpenMP batch workers. The Fortran's
 *     input-change caches (VTST7, ALAST/XL/TLL statics) exist only to
 *     skip recomputation across calls; evaluating everything fresh is
 *     numerically identical to a Fortran cold call, so they were
 *     dropped -- except the per-call reuse of the Legendre/local-time
 *     terms, which survives as flags in the scratch struct because it
 *     saves real work *within* one evaluation.
 *   - The Fortran writes runtime patches into its parameter tables
 *     (GLOBE7 clamps P(25), GLOB7S stamps P(100)); our tables are
 *     const, so the clamps act on local copies -- observable behaviour
 *     is unchanged because those cells are only read via the clamped
 *     locals (P(25)) or are pure set-markers never used in formulas
 *     (P(100)).
 *   - GTS7's anomalous-oxygen DENSU call writes its temperature into
 *     the undeclared scalar T2 -- NOT the output array T(2). That is
 *     part of the reference behaviour; the port reproduces it with a
 *     dummy local.
 *
 * MODEL CONSTANTS: the DATA constants below are part of the model
 * DEFINITION, exactly as fit by NRL (DGTR is *not* pi/180 to double
 * precision, RGAS is the model's own gas constant in its own units).
 * Replacing them with the high-precision spody_const.h siblings would
 * change the model output and break the reference-driver equality, so
 * this file is intentionally exempt from the "all constants live in
 * spody_const.h" rule.
 */
